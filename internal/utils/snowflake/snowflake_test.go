func TestResolveNodeIDPrefersExplicitEnv(t *testing.T) {
	t.Setenv(NodeIDEnvVar, "42")
	t.Setenv(renderServiceIDEnvVar, "srv-production")

	if got := resolveNodeID(); got != 42 {
		t.Fatalf("resolveNodeID() = %d, want 42 (explicit env must win over service hash)", got)
	}
}

func TestResolveNodeIDRejectsOutOfRangeExplicitEnv(t *testing.T) {
	// 越界值不能被截断成一个合法节点号：那会静默落到别的节点空间上。
	// 此处应回退到哈希路径，而非使用 256。
	t.Setenv(NodeIDEnvVar, "256")
	t.Setenv(renderServiceIDEnvVar, "srv-production")

	hashed := resolveNodeID()
	if hashed < 0 || hashed > MaxNodeID {
		t.Fatalf("resolveNodeID() = %d, want a value within [0, %d]", hashed, MaxNodeID)
	}

	t.Setenv(NodeIDEnvVar, "")
	if fallback := resolveNodeID(); fallback != hashed {
		t.Fatalf("out-of-range explicit env should fall back to the hash path: got %d, want %d", hashed, fallback)
	}
}

